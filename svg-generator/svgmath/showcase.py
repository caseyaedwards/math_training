def _plain(s: str) -> str:
    """Strips math markup into readable text for HTML."""
    s = replace_symbols(s)
    out = []
    i = 0
    while i < len(s):
        ch = s[i]
        if ch in "^_" and i + 1 < len(s):
            tag = "sup" if ch == "^" else "sub"
            if s[i + 1] == "{":
                j = s.index("}", i + 2) if "}" in s[i + 2:] else len(s)
                out.append(f"<{tag}>{html.escape(s[i + 2:j])}</{tag}>")
                i = j + 1
            else:
                out.append(f"<{tag}>{html.escape(s[i + 1])}</{tag}>")
                i += 2
            continue
        out.append(html.escape(ch))
        i += 1
    return "".join(out)


def _page(title: str, body: str, depth: int = 0) -> str:
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>{CSS}</style>
</head>
<body>
{body}
<hr>
<p class="nav"><small>Generated by <code>svgmath</code>. Rebuild with <code>python3 -m svgmath showcase</code>.</small></p>
</body>
</html>
"""


def _write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def render_diagram(d: DiagramType, out_dir: str) -> dict:
    """Writes every SVG for one diagram type and returns page metadata."""
    wt = d.build()
    folder = os.path.join(out_dir, d.slug)
    os.makedirs(folder, exist_ok=True)
    steps = []
    for k in range(len(wt.steps)):
        name = f"step-{k + 1:02d}.svg"
        _write(os.path.join(folder, name), wt.render_step(k).to_svg())
        steps.append((name, wt.steps[k]))
    _write(os.path.join(folder, "storyboard.svg"), wt.storyboard().to_svg())
    _write(os.path.join(folder, "animated.svg"), wt.animated().to_svg())
    _write(os.path.join(folder, "final.svg"), wt.final().to_svg())
    return {"d": d, "wt": wt, "steps": steps}


def build(out_dir: str, only: List[str] = None, clean: bool = True) -> List[dict]:
    """Renders all diagrams (or the slugs in `only`) and writes the site."""
    diagrams = all_diagrams()
    if only:
        diagrams = [d for d in diagrams if d.slug in only]
    if clean and not only and os.path.isdir(out_dir):
        for name in os.listdir(out_dir):
            p = os.path.join(out_dir, name)
            if os.path.isdir(p):
                shutil.rmtree(p)
    pages = [render_diagram(d, out_dir) for d in diagrams]
    if only:
        # keep the full index when rebuilding a subset
        pages_for_index = [{"d": d, "wt": d.build(), "steps": None} for d in all_diagrams()]
    else:
        pages_for_index = pages
    for i, pg in enumerate(pages_for_index):
        if pg["steps"] is None:
            continue
        prev_pg = pages_for_index[i - 1] if i > 0 else None
        next_pg = pages_for_index[i + 1] if i + 1 < len(pages_for_index) else None
        _write(os.path.join(out_dir, pg["d"].slug, "index.html"), _diagram_page(pg, prev_pg, next_pg))
    _write(os.path.join(out_dir, "index.html"), _index_page(pages_for_index))
    _write(os.path.join(out_dir, "README.md"), _readme(pages_for_index))
    return pages


def _grouped(pages):
    groups = {}
    for pg in pages:
        groups.setdefault(pg["d"].category, []).append(pg)
    order = sorted(groups, key=lambda c: (CATEGORIES.index(c) if c in CATEGORIES else 99, c))
    return [(c, groups[c]) for c in order]


def _anchor(cat: str) -> str:
    return cat.lower().replace(" ", "-")


def _diagram_page(pg, prev_pg, next_pg) -> str:
    d, wt = pg["d"], pg["wt"]
    nav = ['<a href="../index.html">All diagrams</a>']
    if prev_pg:
        nav.insert(0, f'<a href="../{prev_pg["d"].slug}/index.html">&larr; {html.escape(prev_pg["d"].title)}</a>')
    if next_pg:
        nav.append(f'<a href="../{next_pg["d"].slug}/index.html">{html.escape(next_pg["d"].title)} &rarr;</a>')
    nav_html = '<p class="nav">' + " | ".join(nav) + "</p>"
    parts = [nav_html, f"<h1>{html.escape(wt.title)}</h1>"]
    parts.append(f'<p><b>Category:</b> <a href="../index.html#{_anchor(d.category)}">{html.escape(d.category)}</a>'
                 + (f" &nbsp; <b>Level:</b> {html.escape(wt.level)}" if wt.level else "") + "</p>")
    if wt.concept:
        parts.append(f'<p class="concept">{_plain(wt.concept)}</p>')
    if wt.summary:
        parts.append(f"<p>{_plain(wt.summary)}</p>")
    parts.append("<h2>Step through it</h2>")
    parts.append(f'<div class="stepper" id="stepper" data-steps="{len(pg["steps"])}" style="display:none">'
                 '<p><button class="prev">&larr; Back</button><button class="next">Next &rarr;</button> '
                 '<span class="pos">Step 1 of ' + str(len(pg["steps"])) + '</span> '
                 '<small>(or use the arrow keys)</small></p>'
                 '<img src="step-01.svg" alt="Current step"></div>')
    parts.append("<noscript><p>Turn on JavaScript to step through the diagram, or scroll down.</p></noscript>")
    parts.append("<h2>Watch it</h2>")
    parts.append('<p class="anim"><img src="animated.svg" alt="Animated walkthrough"></p>')
    parts.append("<h2>Step by step</h2>")
    for k, (name, st) in enumerate(pg["steps"]):
        parts.append(f'<div class="step"><h3>Step {k + 1}: {html.escape(st.title)}</h3>'
                     f"<p>{_plain(st.text)}</p>"
                     + (f'<p class="concept">{_plain(st.math)}</p>' if st.math else "")
                     + f'<img src="{name}" alt="Step {k + 1}: {html.escape(st.title)}"></div>')
    parts.append("<h2>All steps at once</h2>")
    parts.append('<p class="board"><a href="storyboard.svg"><img src="storyboard.svg" alt="Storyboard"></a></p>')
    parts.append("<h2>Generate it yourself</h2>")
    parts.append(f"<pre>cd svg-generator\npython3 -m svgmath render {d.slug} --out /tmp/{d.slug}</pre>")
    parts.append(f"<p>Source: <code>{d.module.replace('.', '/')}.py</code></p>")
    parts.append(nav_html)
    parts.append(STEPPER_JS)
    return _page(wt.title, "\n".join(parts), depth=1)


def _index_page(pages) -> str:
    groups = _grouped(pages)
    parts = ["<h1>Math Diagram Showcase</h1>"]
    parts.append(
        f"<p>{len(pages)} diagram types, each with a worked example that builds up one step at a time. "
        "Open a diagram to see the animation, every step with its explanation, and a storyboard of all steps.</p>"
    )
    parts.append('<table class="toc"><tr>')
    for i, (cat, items) in enumerate(groups):
        if i and i % 3 == 0:
            parts.append("</tr><tr>")
        parts.append(f'<td><a href="#{_anchor(cat)}">{html.escape(cat)}</a> ({len(items)})</td>')
    parts.append("</tr></table>")
    for cat, items in groups:
        parts.append(f'<h2 id="{_anchor(cat)}">{html.escape(cat)}</h2><div class="grid">')
        for pg in items:
            d, wt = pg["d"], pg["wt"]
            parts.append(
                f'<div class="card"><a href="{d.slug}/index.html"><img src="{d.slug}/final.svg" '
                f'alt="{html.escape(wt.title)}" loading="lazy"></a>'
                f'<div class="t"><a href="{d.slug}/index.html">{html.escape(wt.title)}</a></div>'
                f'<div class="s">{_plain(wt.concept)}</div>'
                f'<div class="s">{len(wt.steps)} steps</div></div>'
            )
        parts.append("</div>")
    return _page("Math Diagram Showcase", "\n".join(parts))


def _readme(pages) -> str:
    lines = ["# Math Diagram Showcase", "",
             f"{len(pages)} diagram types. Each one is a worked example that builds up one step at a time.", "",
             "Open [index.html](index.html) in a browser for the full site. On GitHub, follow the links below.", ""]
    for cat, items in _grouped(pages):
        lines += [f"## {cat}", "", "| Diagram | Idea | Steps |", "| --- | --- | --- |"]
        for pg in items:
            d, wt = pg["d"], pg["wt"]
            concept = replace_symbols(wt.concept).replace("|", "\\|")
            lines.append(f"| [{wt.title}]({d.slug}/animated.svg) | {concept} | "
                         + " ".join(f"[{k + 1}]({d.slug}/step-{k + 1:02d}.svg)" for k in range(len(wt.steps)))
                         + " |")
        lines.append("")
    return "\n".join(lines)
