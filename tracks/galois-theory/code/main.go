// Galois theory starter kit: solve a quadratic and a cubic by formula,
// permute roots and watch symmetric functions stay put, check the four
// symmetries of Q(sqrt2, sqrt3), walk the derived series of S3, S4 and S5,
// count the real roots of a quintic, and test constructibility.
// Standard library only.
package main

import (
	"fmt"
	"math"
	"math/cmplx"
	"sort"
	"strings"
)

// ---------- Section 1 and 2: formulas ----------

// quadratic returns the two roots of a x^2 + b x + c (real case).
func quadratic(a, b, c float64) (float64, float64) {
	d := math.Sqrt(b*b - 4*a*c)
	return (-b - d) / (2 * a), (-b + d) / (2 * a)
}

// cardano returns u, v and the three roots of x^3 + p x + q = 0.
// The roots are u+v, w u + w^2 v and w^2 u + w v, where w is a cube root of 1.
func cardano(p, q float64) (complex128, complex128, [3]complex128) {
	disc := complex(q*q/4+p*p*p/27, 0)
	u := cmplx.Pow(complex(-q/2, 0)+cmplx.Sqrt(disc), 1.0/3)
	v := complex(-p/3, 0) / u // u v = -p/3 picks the matching cube root
	w := cmplx.Exp(complex(0, 2*math.Pi/3))
	return u, v, [3]complex128{u + v, w*u + w*w*v, w*w*u + w*v}
}

func clean(z complex128) complex128 {
	re, im := real(z), imag(z)
	if math.Abs(re) < 1e-12 {
		re = 0
	}
	if math.Abs(im) < 1e-12 {
		im = 0
	}
	return complex(re, im)
}

// ---------- Section 3: permutations of roots ----------

func permutations(n int) [][]int {
	var out [][]int
	var rec func(cur []int, used []bool)
	rec = func(cur []int, used []bool) {
		if len(cur) == n {
			out = append(out, append([]int(nil), cur...))
			return
		}
		for i := 0; i < n; i++ {
			if !used[i] {
				used[i] = true
				rec(append(cur, i), used)
				used[i] = false
			}
		}
	}
	rec(nil, make([]bool, n))
	return out
}

// ---------- Section 4: the field Q(sqrt2, sqrt3) ----------

// num is a + b sqrt2 + c sqrt3 + d sqrt6 with integer coordinates.
type num struct{ a, b, c, d int }

func mul(x, y num) num {
	return num{
		a: x.a*y.a + 2*x.b*y.b + 3*x.c*y.c + 6*x.d*y.d,
		b: x.a*y.b + x.b*y.a + 3*x.c*y.d + 3*x.d*y.c,
		c: x.a*y.c + x.c*y.a + 2*x.b*y.d + 2*x.d*y.b,
		d: x.a*y.d + x.d*y.a + x.b*y.c + x.c*y.b,
	}
}

// auto is a symmetry given by the signs it puts on sqrt2 and sqrt3.
type auto struct {
	name   string
	s2, s3 int
}

func (f auto) apply(x num) num {
	return num{x.a, f.s2 * x.b, f.s3 * x.c, f.s2 * f.s3 * x.d}
}

func sign(s int) string {
	if s > 0 {
		return "+"
	}
	return "-"
}

// ---------- Section 6: permutation groups ----------

type perm [5]int

func compose(p, q perm) perm { // p after q
	var r perm
	for i := range r {
		r[i] = p[q[i]]
	}
	return r
}

func inverse(p perm) perm {
	var r perm
	for i, x := range p {
		r[x] = i
	}
	return r
}

// generate returns the closure of gens under composition.
func generate(gens []perm) map[perm]bool {
	id := perm{0, 1, 2, 3, 4}
	g := map[perm]bool{id: true}
	queue := []perm{id}
	for len(queue) > 0 {
		x := queue[0]
		queue = queue[1:]
		for _, s := range gens {
			y := compose(s, x)
			if !g[y] {
				g[y] = true
				queue = append(queue, y)
			}
		}
	}
	return g
}

// derived returns the subgroup generated by all commutators a b a^-1 b^-1.
func derived(g map[perm]bool) map[perm]bool {
	seen := map[perm]bool{}
	var comms []perm
	for a := range g {
		for b := range g {
			c := compose(compose(a, b), compose(inverse(a), inverse(b)))
			if !seen[c] {
				seen[c] = true
				comms = append(comms, c)
			}
		}
	}
	return generate(comms)
}

// symmetric returns S_n acting on the first n of 5 points.
func symmetric(n int) map[perm]bool {
	swap := perm{1, 0, 2, 3, 4}
	cycle := perm{0, 1, 2, 3, 4}
	for i := 0; i < n; i++ {
		cycle[i] = (i + 1) % n
	}
	return generate([]perm{swap, cycle})
}

// ---------- Section 7: real roots of a polynomial ----------

func evalPoly(c []float64, x float64) float64 { // c[0] x^n + ... + c[n]
	y := 0.0
	for _, a := range c {
		y = y*x + a
	}
	return y
}

func deriv(c []float64) []float64 {
	n := len(c) - 1
	d := make([]float64, n)
	for i := 0; i < n; i++ {
		d[i] = c[i] * float64(n-i)
	}
	return d
}

func realRoots(c []float64, lo, hi, step float64) []float64 {
	var roots []float64
	d := deriv(c)
	for x := lo; x < hi; x += step {
		if evalPoly(c, x)*evalPoly(c, x+step) < 0 {
			r := x + step/2
			for i := 0; i < 50; i++ { // Newton steps
				r -= evalPoly(c, r) / evalPoly(d, r)
			}
			roots = append(roots, r)
		}
	}
	return roots
}

// divideRoot performs synthetic division of c by (x - r).
func divideRoot(c []float64, r float64) []float64 {
	out := make([]float64, len(c)-1)
	acc := 0.0
	for i := 0; i < len(c)-1; i++ {
		acc = acc*r + c[i]
		out[i] = acc
	}
	return out
}

// ---------- Section 8: constructibility ----------

// rationalRoots tries every p/q with p dividing the constant term and q
// dividing the leading coefficient (integer coefficients only).
func rationalRoots(c []int) []string {
	divisors := func(n int) []int {
		if n < 0 {
			n = -n
		}
		var d []int
		for i := 1; i <= n; i++ {
			if n%i == 0 {
				d = append(d, i)
			}
		}
		return d
	}
	var hits []string
	for _, p := range divisors(c[len(c)-1]) {
		for _, q := range divisors(c[0]) {
			for _, s := range []float64{1, -1} {
				x := s * float64(p) / float64(q)
				y := 0.0
				for _, a := range c {
					y = y*x + float64(a)
				}
				if math.Abs(y) < 1e-12 {
					hits = append(hits, fmt.Sprintf("%g", x))
				}
			}
		}
	}
	return hits
}

func phi(n int) int {
	count := 0
	for k := 1; k <= n; k++ {
		a, b := k, n
		for b != 0 {
			a, b = b, a%b
		}
		if a == 1 {
			count++
		}
	}
	return count
}

func isPowerOfTwo(n int) bool { return n > 0 && n&(n-1) == 0 }

func main() {
	fmt.Println("== Quadratic formula: x^2 - 2x - 3 ==")
	r1, r2 := quadratic(1, -2, -3)
	fmt.Printf("roots %g and %g, sum %g, product %g\n\n", r1, r2, r1+r2, r1*r2)

	fmt.Println("== Cardano: x^3 - 15x - 4 (Bombelli 1572) ==")
	u, v, roots := cardano(-15, -4)
	fmt.Printf("u = cube root of (2 + 11i) = %.4f\n", clean(u))
	fmt.Printf("v = cube root of (2 - 11i) = %.4f\n", clean(v))
	for i, r := range roots {
		res := cmplx.Abs(r*r*r - 15*r - 4)
		fmt.Printf("root %d = %8.4f   |f(root)| = %.1e\n", i+1, real(clean(r)), res)
	}
	fmt.Printf("exact: 4, -2 + sqrt3 = %.4f, -2 - sqrt3 = %.4f\n\n", -2+math.Sqrt(3), -2-math.Sqrt(3))

	fmt.Println("== Shuffle the three roots ==")
	r := []float64{real(roots[0]), real(roots[1]), real(roots[2])}
	e1s, e2s, e3s, lin, delta := map[string]bool{}, map[string]bool{}, map[string]bool{}, map[string]bool{}, map[string]bool{}
	for _, p := range permutations(3) {
		a, b, c := r[p[0]], r[p[1]], r[p[2]]
		e1s[fmt.Sprintf("%.6f", a+b+c)] = true
		e2s[fmt.Sprintf("%.6f", a*b+a*c+b*c)] = true
		e3s[fmt.Sprintf("%.6f", a*b*c)] = true
		lin[fmt.Sprintf("%.6f", a+2*b+3*c)] = true
		delta[fmt.Sprintf("%.6f", (a-b)*(a-c)*(b-c))] = true
	}
	fmt.Printf("over all 6 orders: r1+r2+r3 takes %d value, r1r2+r1r3+r2r3 takes %d, r1r2r3 takes %d\n",
		len(e1s), len(e2s), len(e3s))
	fmt.Printf("r1 + 2 r2 + 3 r3 takes %d values (not symmetric)\n", len(lin))
	fmt.Printf("(r1-r2)(r1-r3)(r2-r3) takes %d values: %v\n\n", len(delta), keys(delta))

	fmt.Println("== The four symmetries of Q(sqrt2, sqrt3) ==")
	autos := []auto{{"id", 1, 1}, {"sigma", -1, 1}, {"tau", 1, -1}, {"sigma tau", -1, -1}}
	fmt.Println("name        sqrt2  sqrt3  sqrt6  respects x*y?")
	x, y := num{1, 2, -1, 3}, num{-2, 1, 4, 1}
	for _, f := range autos {
		ok := f.apply(mul(x, y)) == mul(f.apply(x), f.apply(y))
		fmt.Printf("%-10s  %s      %s      %s      %v\n", f.name, sign(f.s2), sign(f.s3), sign(f.s2*f.s3), ok)
	}
	fmt.Println("every symmetry applied twice gives id: the group is the Klein four-group")
	fmt.Println()

	fmt.Println("== Fifth roots of unity: sigma sends z to z^2 ==")
	k := 1
	var orbit []string
	for i := 0; i < 4; i++ {
		k = k * 2 % 5
		orbit = append(orbit, fmt.Sprintf("z^%d", k))
	}
	z := cmplx.Exp(complex(0, 2*math.Pi/5))
	z2 := z * z
	val := z2*z2*z2*z2 + z2*z2*z2 + z2*z2 + z2 + 1
	fmt.Printf("z -> %s   (order 4, cyclic)\n", strings.Join(orbit, " -> "))
	fmt.Printf("check: z^2 is a root of x^4+x^3+x^2+x+1, residual %.1e\n\n", cmplx.Abs(val))

	fmt.Println("== Derived series (commutator subgroups) ==")
	for _, n := range []int{3, 4, 5} {
		g := symmetric(n)
		sizes := []int{len(g)}
		for i := 0; i < 5 && len(g) > 1; i++ {
			h := derived(g)
			if len(h) == len(g) {
				sizes = append(sizes, len(h))
				break
			}
			g = h
			sizes = append(sizes, len(g))
		}
		verdict := "solvable"
		if sizes[len(sizes)-1] != 1 {
			verdict = "NOT solvable: stuck at A5"
		}
		fmt.Printf("S%d: %v  %s\n", n, sizes, verdict)
	}
	fmt.Println()

	fmt.Println("== The quintic x^5 - 4x + 2 ==")
	quint := []float64{1, 0, 0, 0, -4, 2}
	fmt.Println("Eisenstein at p = 2: 2 divides 0, 0, 0, -4, 2 and 4 does not divide 2 -> irreducible")
	real3 := realRoots(quint, -3, 3, 0.001)
	rest := quint
	for _, x := range real3 {
		fmt.Printf("real root %8.5f   f = %.1e\n", x, evalPoly(quint, x))
		rest = divideRoot(rest, x)
	}
	b, c := rest[1]/rest[0], rest[2]/rest[0]
	re := -b / 2
	im := math.Sqrt(c - b*b/4)
	fmt.Printf("complex pair  %.5f +/- %.5fi\n", re, im)
	fmt.Printf("%d real roots: complex conjugation swaps the other 2\n", len(real3))
	g5 := generate([]perm{{1, 2, 3, 4, 0}, {1, 0, 2, 3, 4}})
	fmt.Printf("a 5-cycle and a swap generate a group of size %d = |S5|\n\n", len(g5))

	fmt.Println("== Ruler and compass ==")
	fmt.Printf("x^3 - 2:        rational roots %v -> irreducible, degree 3\n", rationalRoots([]int{1, 0, 0, -2}))
	fmt.Printf("8x^3 - 6x - 1:  rational roots %v -> irreducible, degree 3\n", rationalRoots([]int{8, 0, -6, -1}))
	cc := math.Cos(20 * math.Pi / 180)
	fmt.Printf("cos 20 deg = %.6f, 8c^3 - 6c - 1 = %.1e\n", cc, 8*cc*cc*cc-6*cc-1)
	fmt.Printf("cube root of 2 = %.6f, cubed = %.6f\n", math.Cbrt(2), math.Pow(math.Cbrt(2), 3))
	fmt.Println("3 is not a power of 2: neither number is constructible")
	var ok []string
	for n := 3; n <= 30; n++ {
		if isPowerOfTwo(phi(n)) {
			ok = append(ok, fmt.Sprint(n))
		}
	}
	fmt.Printf("constructible regular n-gons, n = 3..30: %s\n", strings.Join(ok, " "))
}

func keys(m map[string]bool) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
